function esc(s) { return s.replace(/[.*+?^${}()|[\\]\\]/g, '\\$&'); }
function preserveCase(src, replacement) {
  if (src.toUpperCase() === src) return replacement.toUpperCase();
  if (src[0] && src[0] === src[0].toUpperCase()) return replacement[0].toUpperCase() + replacement.slice(1);
  return replacement;
}

function translateUkToRu(text) {
  let t = text;

  for (const [uk, ru] of phraseMap.sort((a, b) => b[0].length - a[0].length)) {
    t = t.replace(new RegExp(esc(uk), 'gi'), (m) => preserveCase(m, ru));
  }

  for (const [uk, ru] of wordMap.sort((a, b) => b[0].length - a[0].length)) {
    t = t.replace(new RegExp(`\\b${esc(uk)}\\b`, 'gi'), (m) => preserveCase(m, ru));
  }

  t = t
    .replace(/і/g, 'и').replace(/І/g, 'И')
    .replace(/ї/g, 'и').replace(/Ї/g, 'И')
    .replace(/є/g, 'е').replace(/Є/g, 'Е')
    .replace(/ґ/g, 'г').replace(/Ґ/g, 'Г');

  return t;
}

let changed = 0;
for (const post of posts) {
  const uk = post?.translations?.uk?.content;
  const ru = post?.translations?.ru?.content;
  if (!uk || !ru) continue;

  const nextRu = {};
  for (const key of Object.keys(uk)) {
    if (typeof uk[key] === 'string') {
      const translated = translateUkToRu(uk[key]);
      nextRu[key] = translated;
      if (ru[key] !== translated) changed++;
    } else {
      nextRu[key] = ru[key] ?? uk[key];
    }
  }

  if (typeof nextRu.para1 === 'string') nextRu.intro = nextRu.para1;
  post.translations.ru.content = nextRu;
}

